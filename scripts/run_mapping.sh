#!/usr/bin/env bash
# Build the warehouse map with Cartographer.
#
# Drives the robot up and down the aisle on a fixed velocity profile rather than
# through Nav2. Nav2 needs a map to plan against, which is what this is
# producing, and teleoperating by hand makes the map unreproducible.
#
# The traverse is deliberately run twice, out and back. A single pass gives
# Cartographer no loop closure at all in a corridor, and the accumulated drift
# over 24 m shows up as an aisle that is visibly not straight.

set -euo pipefail

RESULTS="${1:-results}"
MAP_NAME="${MAP_NAME:-warehouse}"
SPEED="${SPEED:-0.4}"
LEG_SECONDS="${LEG_SECONDS:-60}"

mkdir -p "${RESULTS}"

cleanup() {
  local status=$?
  echo "--- stopping the robot"
  ros2 topic pub --once /cmd_vel geometry_msgs/msg/Twist \
    '{linear: {x: 0.0}, angular: {z: 0.0}}' > /dev/null 2>&1 || true
  [[ -n "${SIM_PID:-}" ]] && kill -- -"${SIM_PID}" 2>/dev/null || true
  [[ -n "${SLAM_PID:-}" ]] && kill -- -"${SLAM_PID}" 2>/dev/null || true
  pkill -f "gz sim" 2>/dev/null || true
  wait 2>/dev/null || true
  exit "${status}"
}
trap cleanup EXIT INT TERM

echo "--- starting simulation without localisation"
# The simulation launch brings up AMCL, which would fight Cartographer for
# map -> odom. Only the robot and the EKF are wanted here.
setsid ros2 launch amr_bringup simulation.launch.py headless:=true \
  > "${RESULTS}/mapping_sim.log" 2>&1 &
SIM_PID=$!
sleep 15

echo "--- stopping AMCL so Cartographer owns map -> odom"
ros2 lifecycle set /amcl deactivate > /dev/null 2>&1 || true

echo "--- starting Cartographer"
setsid ros2 launch amr_localisation mapping.launch.py \
  > "${RESULTS}/cartographer.log" 2>&1 &
SLAM_PID=$!
sleep 10

drive() {
  local vx="$1" duration="$2"
  local deadline=$((SECONDS + duration))
  while (( SECONDS < deadline )); do
    ros2 topic pub --once /cmd_vel geometry_msgs/msg/Twist \
      "{linear: {x: ${vx}}, angular: {z: 0.0}}" > /dev/null 2>&1
    sleep 0.1
  done
}

turn() {
  local wz="$1" duration="$2"
  local deadline=$((SECONDS + duration))
  while (( SECONDS < deadline )); do
    ros2 topic pub --once /cmd_vel geometry_msgs/msg/Twist \
      "{linear: {x: 0.0}, angular: {z: ${wz}}}" > /dev/null 2>&1
    sleep 0.1
  done
}

echo "--- traverse 1: east"
drive "${SPEED}" "${LEG_SECONDS}"
echo "--- turning"
turn 0.5 13
echo "--- traverse 2: west, for loop closure"
drive "${SPEED}" "${LEG_SECONDS}"
turn 0.5 13

echo "--- finishing the trajectory and writing the map"
ros2 service call /finish_trajectory cartographer_ros_msgs/srv/FinishTrajectory \
  "{trajectory_id: 0}" || true
sleep 5

ros2 run nav2_map_server map_saver_cli \
  -f "${RESULTS}/${MAP_NAME}" --ros-args -p save_map_timeout:=20.0

echo
echo "--- map written to ${RESULTS}/${MAP_NAME}.pgm and .yaml"
echo "To use it for navigation, copy both into simulation/maps/ and rebuild:"
echo "    cp ${RESULTS}/${MAP_NAME}.* simulation/maps/"
echo "    colcon build --packages-select amr_bringup"
echo
echo "Note: simulation/maps/warehouse.pgm as shipped is the GEOMETRIC reference"
echo "map generated by simulation/generate_world.py, not a SLAM product. The"
echo "map produced here is the real one and will differ from it by Cartographer's"
echo "own error, which is the point of comparing them."
